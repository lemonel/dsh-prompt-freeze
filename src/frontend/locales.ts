// Only standalone previews/tests use this helper. Production receives t from slots.
function standaloneTranslator(language: string = 'zh'): Translator {
  const dict: Readonly<Record<string, string>> = dictionaries[language] ?? en
  return (key, params) => (dict[key] ?? (en as Readonly<Record<string, string>>)[key] ?? key).replace(/\{(\w+)\}/g, (match, name) => params && name in params ? String(params[name]) : match)
}
